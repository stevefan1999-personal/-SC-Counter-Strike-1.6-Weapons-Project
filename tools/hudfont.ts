// Writes the glyph advances of the face that Sven Co-op draws HudMessage text with, so the server can measure a name
// in pixels and pack the kill-feed icons against it (docs/hud.md, "Kill feed").
// Usage: deno run -R -W tools/hudfont.ts <out.as> <font.ttf>...   (just hud-font passes the client's candidates)
// Self-check: deno test -R -E tools/
//
// The client's VGUI2 font code (Sven hw.so 0x1CA070) opens the face with FreeType and selects the Apple Roman cmap;
// a face without one cannot be created, and VGUI2 tries the next face. The pixel size makes the OS/2 Windows ascent
// plus descent as high as the font tall. Each byte of the text is one glyph code, and each glyph advances by its
// hinted advance, rounded to whole pixels.

const MAC_PLATFORM = 1;
const MAC_ROMAN_ENCODING = 0;
const BYTE_TABLE_FORMAT = 0;
const GLYPH_CODES = 256;
const ADVANCES_PER_LINE = 16;

// HudMessage font tall: VGUI2 scales the scheme tall 12 of CreditsFont by the screen height over the 480 base and
// caps it at 128 (sven-client-hudtext.md 3).
const SCHEME_TALL = 12;
const BASE_HEIGHT = 480;
const MAX_TALL = 128;

// FreeType 26.6 and 16.16 fixed point.
const SUBPIXELS = 64;
const FIXED_ONE = 65536;

export type HudFont = { unitsPerEm: number; cellUnits: number; advances: number[] };

export class NoAppleRomanCmap extends Error {}

export function parseFont(bytes: Uint8Array): HudFont {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const tables = new Map(
    Array.from({ length: view.getUint16(4) }, (_, index) => 12 + index * 16).map((record) => [
      new TextDecoder().decode(bytes.subarray(record, record + 4)),
      view.getUint32(record + 8),
    ]),
  );
  const table = (tag: string) => {
    const offset = tables.get(tag);
    if (offset === undefined) throw new Error(`the font has no ${tag} table`);
    return offset;
  };
  const cmap = table("cmap");
  const macRoman = Array.from({ length: view.getUint16(cmap + 2) }, (_, index) => cmap + 4 + index * 8)
    .find((record) => view.getUint16(record) === MAC_PLATFORM && view.getUint16(record + 2) === MAC_ROMAN_ENCODING);
  if (macRoman === undefined) throw new NoAppleRomanCmap("the font has no Apple Roman cmap, so Sven cannot use it");
  const subtable = cmap + view.getUint32(macRoman + 4);
  if (view.getUint16(subtable) !== BYTE_TABLE_FORMAT) throw new Error("the Apple Roman cmap is not a byte table");
  const head = table("head"), hhea = table("hhea"), os2 = table("OS/2"), hmtx = table("hmtx");
  // hw.so falls back to the hhea extent when the Windows metrics are 0.
  const cellUnits = view.getUint16(os2 + 74) + view.getUint16(os2 + 76) ||
    view.getInt16(hhea + 4) - view.getInt16(hhea + 6);
  const lastMetric = view.getUint16(hhea + 34) - 1;
  const advance = (glyph: number) => view.getUint16(hmtx + 4 * Math.min(glyph, lastMetric));
  const glyphs = bytes.subarray(subtable + 6, subtable + 6 + GLYPH_CODES);
  return { unitsPerEm: view.getUint16(head + 18), cellUnits, advances: [...glyphs].map(advance) };
}

const fontTall = (screenHeight: number) => Math.min(Math.floor(SCHEME_TALL * screenHeight / BASE_HEIGHT), MAX_TALL);

// FT_Set_Pixel_Sizes argument of hw.so: the em size that makes the Windows ascent plus descent as high as the tall.
const pixelsPerEm = (font: HudFont, screenHeight: number) =>
  Math.floor(fontTall(screenHeight) * font.unitsPerEm / font.cellUnits);

// The same sum as TextWidth in scripts/cs16/killfeed.as: FT_DivFix for the x scale, FT_MulFix for each advance, then
// the whole-pixel rounding of the hinted metrics.
export function lineWidth(font: HudFont, text: Uint8Array, screenHeight: number): number {
  const scale = Math.floor(
    (pixelsPerEm(font, screenHeight) * SUBPIXELS * FIXED_ONE + Math.floor(font.unitsPerEm / 2)) / font.unitsPerEm,
  );
  return text.reduce((sum, code) => {
    const scaled = Math.floor((font.advances[code] * scale + FIXED_ONE / 2) / FIXED_ONE);
    return sum + Math.floor((scaled + SUBPIXELS / 2) / SUBPIXELS);
  }, 0);
}

export function renderAngelScript(font: HudFont, source: string): string {
  const rows = Array.from(
    { length: GLYPH_CODES / ADVANCES_PER_LINE },
    (_, row) => "    " + font.advances.slice(row * ADVANCES_PER_LINE, (row + 1) * ADVANCES_PER_LINE).join(", "),
  );
  return [
    `// Generated by tools/hudfont.ts from ${source}. Do not edit; run just hud-font.`,
    "// Glyph advances, in font units, of the face that Sven draws HudMessage text with, by byte (Apple Roman cmap).",
    "namespace CS16HUD",
    "{",
    `  const int TEXT_FONT_UNITS_PER_EM = ${font.unitsPerEm};`,
    `  const int TEXT_FONT_CELL_UNITS = ${font.cellUnits}; // OS/2 Windows ascent + descent`,
    "  const array<int> TEXT_GLYPH_ADVANCES =",
    "  {",
    rows.join(",\n"),
    "  };",
    "}",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const [outPath, ...candidates] = Deno.args;
  if (candidates.length === 0) throw new Error("usage: hudfont.ts <out.as> <font.ttf>...");
  for (const path of candidates) {
    try {
      const font = parseFont(await Deno.readFile(path));
      await Deno.writeTextFile(outPath, renderAngelScript(font, path.split("/").at(-1)!));
      console.log(`wrote ${outPath} from ${path}: ${font.unitsPerEm} units per em, cell ${font.cellUnits}`);
      Deno.exit(0);
    } catch (error) {
      if (!(error instanceof NoAppleRomanCmap)) throw error;
      console.warn(`${path}: ${error.message}; the client falls back to the next face`);
    }
  }
  throw new Error("no candidate face has an Apple Roman cmap");
}
